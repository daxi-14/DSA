class Solution {
    public long maxAlternatingSum(int[] nums) {
        long[] squares = new long[nums.length];

        for (int i = 0; i < nums.length; i++) {
            squares[i] = (long) nums[i] * nums[i];
        }

        Arrays.sort(squares);

        long ans = 0;
        int left = 0, right = nums.length - 1;

        while (left < right) {
            ans += squares[right] - squares[left];
            left++;
            right--;
        }

        if (left == right) {
            ans += squares[left];
        }

        return ans;
    }
}

